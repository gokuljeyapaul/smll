/**
 * Shared e2e helpers for the S2 installable/offline shell (A11) and the
 * share target (A08): wait for the service worker and its precache to be
 * fully ready, and read the build's own precache list.
 */
import { expect, type Page } from '@playwright/test';

export interface ShellState {
  /** Entries listed by dist/precache-manifest.js (-1 while it 404s). */
  manifestCount: number;
  /** Entries actually in the app-shell cache (-1 while it is empty). */
  cachedCount: number;
  /** True once a service worker controls this origin. */
  swActive: boolean;
}

export async function readShellState(page: Page): Promise<ShellState> {
  return page.evaluate(async () => {
    let manifestCount = -1;
    let cachedCount = -1;
    let swActive = false;
    try {
      const res = await fetch('/precache-manifest.js');
      if (res.ok) {
        const text = await res.text();
        const arr = text.slice(text.indexOf('['), text.lastIndexOf(']') + 1);
        manifestCount = (JSON.parse(arr) as unknown[]).length;
      }
    } catch {
      manifestCount = -1;
    }
    try {
      if (typeof caches !== 'undefined') {
        const names = await caches.keys();
        const shell = names.find((n) => n.startsWith('precache'));
        if (shell) cachedCount = (await (await caches.open(shell)).keys()).length;
      }
    } catch {
      cachedCount = -1;
    }
    try {
      const reg = await navigator.serviceWorker.getRegistration();
      swActive = !!reg && !!(reg.active || reg.installing || reg.waiting);
    } catch {
      swActive = false;
    }
    return { manifestCount, cachedCount, swActive };
  });
}

/**
 * Wait until the service worker is active AND every entry the build's
 * precache manifest lists is actually cached (the app shell is complete —
 * A11 "after first load" and the precondition for going offline).
 */
export async function waitForAppShellReady(page: Page): Promise<ShellState> {
  let last: ShellState = { manifestCount: -1, cachedCount: -1, swActive: false };
  await expect
    .poll(
      async () => {
        last = await readShellState(page);
        return last.swActive && last.manifestCount > 0 && last.cachedCount === last.manifestCount;
      },
      { timeout: 120_000, message: 'service worker active with a complete precache' },
    )
    .toBe(true);
  return last;
}

/**
 * Read the build's own precache manifest (dist/precache-manifest.js,
 * generated by scripts/build_pwa_precache.mjs): [{url, revision, cacheKey}].
 * Empty list while the S2 app shell does not exist (RED state: 404).
 */
export async function readPrecacheEntries(page: Page): Promise<
  { url: string; revision: string; cacheKey: string }[]
> {
  return page.evaluate(async () => {
    try {
      const text = await (await fetch('/precache-manifest.js')).text();
      return JSON.parse(text.slice(text.indexOf('['), text.lastIndexOf(']') + 1));
    } catch {
      return [];
    }
  });
}

/** The share-target POST URL the manifest declares (must match it). */
export const SHARE_TARGET_URL = '/share-target';

/**
 * Post a real multipart share-target form from the page, THROUGH the
 * service worker (the page's own fetch is intercepted by the SW's fetch
 * event — the same handler Android's share sheet hits).
 */
export async function postShareTargetForm(
  page: Page,
  file: { name: string; type: string; bytes: string } | null,
): Promise<{ status: number; ok: boolean }> {
  return page.evaluate(
    async ({ url, file }) => {
      const body = new FormData();
      if (file) {
        const buf = Uint8Array.from(atob(file.bytes), (c) => c.charCodeAt(0));
        body.append('image', new File([buf], file.name, { type: file.type }));
      }
      const res = await fetch(url, { method: 'POST', body });
      return { status: res.status, ok: res.ok };
    },
    { url: SHARE_TARGET_URL, file },
  );
}

/** Read a file under the project root into base64 for posting inside the page. */
export async function readFixtureB64(path: string): Promise<string> {
  const { readFileSync } = await import('node:fs');
  const { join, dirname } = await import('node:path');
  const { fileURLToPath } = await import('node:url');
  const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
  return readFileSync(join(root, path)).toString('base64');
}
